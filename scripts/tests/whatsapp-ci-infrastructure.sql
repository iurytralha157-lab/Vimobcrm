create schema extensions;
create extension pgcrypto with schema extensions;
create extension pg_trgm with schema extensions;
create extension "uuid-ossp" with schema extensions;
create extension pgtap with schema extensions;
grant usage on schema extensions to anon,authenticated,service_role;
create schema auth;
create table auth.users(id uuid primary key,instance_id uuid,aud text,role text,email text,
 encrypted_password text,email_confirmed_at timestamptz,raw_app_meta_data jsonb,raw_user_meta_data jsonb,
 created_at timestamptz,updated_at timestamptz,is_sso_user boolean not null default false,
 confirmation_token text default '',recovery_token text default '',email_change_token_new text default '',
 email_change text default '',is_anonymous boolean not null default false);
create table auth.sessions(id uuid primary key,user_id uuid references auth.users(id) on delete cascade,
 created_at timestamptz default now(),updated_at timestamptz default now(),not_after timestamptz);
create function auth.jwt() returns jsonb language sql stable as
 $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
create function auth.uid() returns uuid language sql stable as
 $$select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),auth.jwt()->>'sub')::uuid$$;
create function auth.role() returns text language sql stable as
 $$select coalesce(nullif(current_setting('request.jwt.claim.role',true),''),auth.jwt()->>'role')$$;
grant usage on schema auth to anon,authenticated,service_role;
grant execute on all functions in schema auth to anon,authenticated,service_role;
create schema storage;
create table storage.buckets(id text primary key,name text,public boolean default false,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),
 name text,owner uuid,owner_id text,metadata jsonb default '{}',created_at timestamptz default now(),updated_at timestamptz default now());
alter table storage.objects enable row level security;
create function storage.foldername(name text) returns text[] language sql immutable as
 $$select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1]$$;
grant usage on schema storage to anon,authenticated,service_role;
grant all on storage.objects,storage.buckets to service_role;
create schema realtime;
create publication supabase_realtime;
create table realtime.messages(id bigint generated by default as identity primary key,
 payload jsonb,event text,topic text,private boolean default true,extension text default 'broadcast',
 inserted_at timestamptz default now(),updated_at timestamptz default now());
alter table realtime.messages enable row level security;
create function realtime.topic() returns text language sql stable as $$select current_setting('realtime.topic',true)$$;
create function realtime.send(payload jsonb,event text,topic text,private boolean default true)
 returns void language sql security definer set search_path='' as
 $$insert into realtime.messages(payload,event,topic,private,extension) values($1,$2,$3,$4,'broadcast')$$;
grant usage on schema realtime to authenticated,service_role;
grant select on realtime.messages to authenticated;
grant all on realtime.messages to service_role;
grant execute on all functions in schema realtime to authenticated,service_role;
